import * as React from "react";
import {
  ColumnDef,
  SortingState,
  flexRender,
  getCoreRowModel,
  getPaginationRowModel,
  getSortedRowModel,
  useReactTable,
} from "@tanstack/react-table";

import {
  Table,
  TableBody,
  TableCell,
  TableHead,
  TableHeader,
  TableRow,
} from "@/components/ui/table";

import { DataTablePagination } from "../../components/ui/pagination";
import { useNavigate } from "react-router-dom";
import { Button } from "@/components/ui/button";

interface DataTableProps<TData, TValue> {
  columns: ColumnDef<TData, TValue>[];
  data: TData[];
}

export function ChurnPredictionTable<TData extends { driverDetailsId: string; predictionId: string }, TValue>({
  columns,
  data
}: DataTableProps<TData, TValue>) {
  const [sorting, setSorting] = React.useState<SortingState>([]);
  const [rowSelection, setRowSelection] = React.useState({});
  const [selectedRowsInfo, setSelectedRowsInfo] = React.useState<
    { driverDetailsId: number; predictionId: number }[]
  >([]);

  const navigate = useNavigate();

  const table = useReactTable({
    data,
    columns,
    getCoreRowModel: getCoreRowModel(),
    getPaginationRowModel: getPaginationRowModel(),
    getSortedRowModel: getSortedRowModel(),
    onSortingChange: setSorting,
    onRowSelectionChange: setRowSelection,
    initialState: {
      pagination: { pageSize: 5 },
    },
    state: {
      sorting,
      rowSelection,
    },
  });

  React.useEffect(() => {
    const selectedRows = table.getSelectedRowModel().rows;
    const rowsData = selectedRows.map((row) => ({
      driverDetailsId: row.original.driverDetailsId,
      predictionId: row.original.predictionId,
    }));
    setSelectedRowsInfo(rowsData);
  }, [rowSelection, table]);

  return (
    <div className="w-full flex flex-col">
      <div className="flex justify-end pt-2 pb-4">
        {selectedRowsInfo.length > 0 && (
          <Button
            onClick={() => {
              navigate("/manage-offers/add", { state: { selectedRows: selectedRowsInfo } });
            }}
          >
            Add Custom Offer
          </Button>
        )}
      </div>
      <div className="rounded-md border w-full">
        <Table>
          <TableHeader>
            {table.getHeaderGroups().map((headerGroup) => (
              <TableRow key={headerGroup.id}>
                {headerGroup.headers.map((header) => (
                  <TableHead key={header.id}>
                    {header.isPlaceholder
                      ? null
                      : flexRender(
                          header.column.columnDef.header,
                          header.getContext()
                        )}
                  </TableHead>
                ))}
              </TableRow>
            ))}
          </TableHeader>
          <TableBody>
            {table.getRowModel().rows?.length ? (
              table.getRowModel().rows.map((row) => (
                <TableRow
                  key={row.id}
                  data-state={row.getIsSelected() && "selected"}
                >
                  {row.getVisibleCells().map((cell) => (
                    <TableCell key={cell.id}>
                      {flexRender(
                        cell.column.columnDef.cell,
                        cell.getContext()
                      )}
                    </TableCell>
                  ))}
                </TableRow>
              ))
            ) : (
              <TableRow>
                <TableCell
                  colSpan={columns.length}
                  className="h-24 text-center"
                >
                  No results.
                </TableCell>
              </TableRow>
            )}
          </TableBody>
        </Table>
      </div>

      <div className="space-x-2 py-4">
        <DataTablePagination table={table} />
      </div>
    </div>
  );
}
